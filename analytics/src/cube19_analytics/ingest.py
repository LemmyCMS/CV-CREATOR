"""Ingestion - turn whatever comes out of Cube19/Bullhorn into a Dataset.

Real exports never match a spec. Column names differ per tenant, per report screen and
per person who ran the export. So the loader matches headers loosely, records what it
could not map, and keeps going - a mapping report you can read beats a stack trace on
row 40,000.

Canonical CSV shapes are documented in data/sample/ (generated by
scripts/generate_sample_data.py), which doubles as the format spec to hand whoever runs
the extraction.
"""

