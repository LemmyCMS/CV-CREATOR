def load_status_map(path: str | Path | None) -> dict[str, str]:
    """Load a tenant status map (JSON: {"Gentis status": "canonical_stage"}).

    Merged over the defaults, so a partial map is fine.
    """
    mapping = dict(DEFAULT_STATUS_MAP)
    if path and Path(path).exists():
        with open(path, encoding="utf-8") as fh:
            mapping.update({k.strip().lower(): v for k, v in json.load(fh).items()})
    return mapping


def normalise_stage(status: str, mapping: dict[str, str] | None = None) -> Stage | None:
    """Map a tenant status string to a canonical stage. None = unmapped."""
    mapping = mapping or DEFAULT_STATUS_MAP
    key = re.sub(r"\s+", " ", (status or "").strip().lower())
    value = mapping.get(key)
    if value is None:
        return None
    try:
        return Stage(value)
    except ValueError:
        return None


@dataclass
class MappingReport:
    """What the loader understood, and what it did not. Read this before the numbers."""

    files_read: list[str] = field(default_factory=list)
    rows_read: dict[str, int] = field(default_factory=dict)
    rows_skipped: dict[str, int] = field(default_factory=dict)
    unmapped_statuses: dict[str, int] = field(default_factory=dict)
    unmapped_columns: dict[str, list[str]] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)

    def render(self) -> str:
        lines = ["Ingestion report", "=" * 40]
        for f in self.files_read:
            lines.append(f"  {f}: {self.rows_read.get(f, 0)} rows"
                         + (f" ({self.rows_skipped[f]} skipped)" if self.rows_skipped.get(f) else ""))
        if self.unmapped_statuses:
            lines.append("\nUNMAPPED STATUSES - these rows were dropped from the funnel:")
            for status, n in sorted(self.unmapped_statuses.items(), key=lambda kv: -kv[1]):
                lines.append(f"  {status!r}: {n} rows")
            lines.append("  -> add them to your status map (docs/06 item 1.1)")
        if self.unmapped_columns:
            lines.append("\nUNRECOGNISED COLUMNS (ignored):")
            for f, cols in self.unmapped_columns.items():
                lines.append(f"  {f}: {', '.join(cols)}")
        for w in self.warnings:
            lines.append(f"\nWARNING: {w}")
        return "\n".join(lines)


